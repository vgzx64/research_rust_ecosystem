def read_json_file(f):
    jsonList = []
    num_unsafe = 0
    num_safe = 0
    with open(f) as file:  
        jsonObj = ""  
        lines = file.readlines()
        num_unsafe = int(lines[1].split(': ')[1])
        num_safe = int(lines[0].split(': ')[1])
        for line in lines:
            if line[0] == "#":
                continue
            elif line!="}\n":
                jsonObj += line
            else:
                jsonObj += line
                jsonDict = json.loads(jsonObj)
                jsonList.append(jsonDict)
                jsonObj = ""
    return jsonList, num_safe, num_unsafe

def read_json_list_file(f):
    jsonList = []
    num_unsafe = 0
    with open(f) as file:  
        jsonObj = ""  
        lines = file.readlines()
        num_unsafe = int(lines[1].split(': ')[1])
        for line in lines:
            if line[0] == "#":
                continue
            elif line!="]\n":
                jsonObj += line
            else:
                jsonObj += line
                jsonDict = json.loads(jsonObj)
                if len(jsonDict)>0:
                    jsonList.extend(jsonDict)
                jsonObj = ""
    return jsonList, num_unsafe

def read_json_list_file_v3(f):
    jsonList = []
    num_unsafe = 0
    with open(f) as file:
        lines = file.readlines()
        num_unsafe = int(lines[1].split(': ')[1])
        for line in lines:
            if line[0] == "#":
                continue
            line = line.strip()
            if line:
                jsonDict = json.loads(line)
                if isinstance(jsonDict, list) and len(jsonDict) > 0:
                    jsonList.extend(jsonDict)
                elif isinstance(jsonDict, dict):
                    jsonList.append(jsonDict)
    return jsonList, num_unsafe

_SPAN_RE = re.compile(r'^(.*?\.rs):\s*(?:(\d+):\d+:\s*)?(\d+)[-:](\d+)$')

def parse_span(span):
    """Returns (span_start, span_end, path) from either v2 or v3 format.
    
    V3 spans use absolute worktree paths; normalizes them to relative
    so the DB path matches file_change.old_path/new_path.
    """
    m = _SPAN_RE.match(span)
    if m:
        path = m.group(1)
        start = m.group(3)
        end = m.group(4)
        # ponytail: v3 paths are absolute worktree paths like
        # /mnt/.../repos_worktree/project/src/foo.rs. Strip the prefix
        # so path matches the relative paths in file_change table.
        if '/repos_worktree/' in path:
            path = path.split('repos_worktree/', 1)[1]
            path = path.split('/', 1)[1]
        return start, end, path
    # ponytail: shouldn't happen with current data, but keep as safety net
    parts = span.split(': ')
    path = parts[0]
    rest = parts[-1]
    start, end = rest.split('-') if '-' in rest else (rest, rest)
    start = start.strip()
    return start, end, path

def format_functions(f, cve_id, commit_hash):
    jsonList, num_safe, num_unsafe = read_json_file(f)
    df = pd.DataFrame.from_records(jsonList)
    if not df.empty:
        df = df[df.apply(lambda x: "/.cargo/" not in x.header_span and "/rustc/" not in x.header_span, axis=1)]
    if not df.empty:
        df = df[df.apply(lambda x: ".rs" in x.header_span, axis=1) ]
    if not df.empty:
        # remove #[derive()] functions auto-generated by compilers
        df = df[df.apply(lambda x: x.header_span != x.body_span, axis=1) ]

    if df.empty:
        return df,0, 0
    df['span_start'], df['span_end'], df['path'] = zip(*df['header_span'].map(parse_span))
    df["cve_id"] = cve_id
    df["hash"] = commit_hash
    df = df[ordered_columns]
    num_safe = len(df[df['unsafety']==False])
    num_unsafe = len(df[df['unsafety']==True])
    return df,num_safe, num_unsafe

def format_blocks(f, cve_id, commit_hash):
    try:
        jsonList, num_unsafe = read_json_list_file_v3(f)
        if not jsonList:
            jsonList, num_unsafe = read_json_list_file(f)
    except Exception:
        jsonList, num_unsafe = read_json_list_file(f)

    df = pd.DataFrame.from_records(jsonList)
    if not df.empty:
        # Exclude code from installed crates
        df = df[df.apply(lambda x: "/.cargo/" not in x.block_span and "/rustc/" not in x.block_span, axis=1)]
    if not df.empty:
        # Include only Rust code files
        df = df[df.apply(lambda x: ".rs" in x.block_span, axis=1)]
    if df.empty:
        return df, 0
    df['span_start'], df['span_end'], df['path'] = zip(*df['block_span'].map(parse_span))
    df["hash"] = commit_hash
    df["cve_id"] = cve_id
    df = df[ordered_columns_block]
    num_unsafe = len(df)
    return df, num_unsafe

def format_traits(f, package, cve_id, commit_hash):
    jsonList = read_json_file(f)
    df = pd.DataFrame.from_records(jsonList)
    if df.empty:
        return df
    df['fn_id'] = df['name'].apply(lambda x : hash(x+cve_id) & sys.maxsize)
    def get_loc(x):
        start = x.find("line \"")+6
        return x[start:-1]
    df['span'] = df['loc'].apply(lambda x: get_loc(x))
    del df["loc"]
    del df["safe"]
    df["package"] = package
    df["cve_id"] = cve_id
    df["hash"] = commit_hash
    df["unsafety"] = True
    df = df[ordered_columns]
    return df

def drop_tables():
    # drop all unsafe related tables
    mycursor = db.conn.cursor()
    mycursor.execute("DROP TABLE IF EXISTS unsafe_block;")
    mycursor.execute("DROP TABLE IF EXISTS unsafe_block_fix;")
    mycursor.execute("DROP TABLE IF EXISTS function;")
    mycursor.execute("DROP TABLE IF EXISTS function_fix;")
    mycursor.execute("DROP TABLE IF EXISTS total_safe_unsafe;")

# recursive glob finds files at any depth, handling v2's flat
# {project}/{cve}/{hash}/{crate}/ layout and v3's deeper
# {project}/{cve}/{hash}/{hash}/{cve}/{crate_hash}/ layout transparently.
def format_compile(analysis_dir, cve_id, hash):
    total_fn_safe = 0
    total_fn_unsafe = 0
    total_block_unsafe = 0
    df_func = pd.DataFrame()
    df_block = pd.DataFrame()

    for f_func in glob.glob(os.path.join(analysis_dir, '**', '01_functions*'), recursive=True):
        # Filter out non-crate-file paths (keep only the deepest nested files)
        if os.path.dirname(f_func) == analysis_dir:
            continue
        df, num_safe, num_unsafe = format_functions(f_func, cve_id, hash)
        if not df.empty:
            df_func = pd.concat([df_func, df])
        total_fn_safe += num_safe
        total_fn_unsafe += num_unsafe

    for f_block in glob.glob(os.path.join(analysis_dir, '**', '02_blocks_in_function*'), recursive=True):
        if os.path.dirname(f_block) == analysis_dir:
            continue
        df, num_unsafe = format_blocks(f_block, cve_id, hash)
        if not df.empty:
            df_block = pd.concat([df_block, df])
        total_block_unsafe += num_unsafe

    return df_func, df_block, total_fn_safe, total_fn_unsafe, total_block_unsafe



@click.command()
@click.argument("commitfile", type=click.STRING)
def main(commitfile):
    drop_tables()

    df_fixes = pd.read_csv(commitfile)
    df_fixes.drop_duplicates(subset =['hash', 'repo_url'], keep = 'first', inplace = True)
    df_safe_cnt = pd.DataFrame(columns=["cve_id", "hash", "safe_func", "unsafe_func", "unsafe_block"])
    compile_failed = 0
    for _, row in df_fixes.iterrows():
        repo_url = row["repo_url"]
        cve_id = str(row["cve_id"])
        hash = row["hash"]
        full_project_name = get_full_project_name(repo_url)
        
        analysis_dir = f"{compiler_result}/{full_project_name}/{cve_id}/{hash}/"
        print(analysis_dir)
        if os.path.exists(analysis_dir):
            df_func, df_block, total_fn_safe, total_fn_unsafe, total_block_unsafe = format_compile(analysis_dir, cve_id, hash)
            write_database("function", df_func)
            write_database("unsafe_block", df_block)
            df_safe_cnt.loc[len(df_safe_cnt)] = {
                "cve_id": cve_id, 
                "hash":hash, 
                "safe_func":total_fn_safe, 
                "unsafe_func":total_fn_unsafe, 
                "unsafe_block":total_block_unsafe
            }
        else:
            compile_failed += 1

        analysis_dir = f"{compiler_result}/{full_project_name}/{cve_id}_fix/{hash}/"
        print(analysis_dir)
        if os.path.exists(analysis_dir):
            df_func, df_block, total_fn_safe, total_fn_unsafe, total_block_unsafe = format_compile(analysis_dir, cve_id, hash)
            write_database("unsafe_block_fix", df_block)
            write_database("function_fix", df_func)
        else:
            compile_failed += 1
        
    df_safe_cnt = df_safe_cnt[ordered_columns_num]
    write_database("total_safe_unsafe",df_safe_cnt)
    
if __name__ == '__main__':
    main()