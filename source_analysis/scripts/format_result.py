import sys
import os
from pathlib import Path
import pandas as pd
import json
import click
import re
sys.path.append('../../utils')
import database as db
from database import write_database
from utils import get_full_project_name

ordered_columns = ['cve_id', 'hash', "path", "name", "span_start", "span_end", "unsafety"]
ordered_columns_block = ['cve_id', 'hash', 'fn_id', 'path', "span_start", "span_end", "unsafety"]
ordered_columns_num = ['cve_id', 'hash', 'safe_func', 'unsafe_func', 'unsafe_block']
compiler_result = "../../compiler_result_v3"

span_pattern = re.compile(r'^(?P<path>.+?):\s*(?P<span_start>\d+)-(?P<span_end>\d+)$')
trait_loc_pattern = re.compile(r'file:\s*"(?P<path>[^"]+)"\s+line\s+"(?P<span_start>\d+)-(?P<span_end>\d+)"')

def _read_metadata_value(line):
    match = re.search(r':\s*(\d+)\s*$', line)
    return int(match.group(1)) if match else 0

def read_json_file(f):
    json_list = []
    num_safe = 0
    num_unsafe = 0
    with open(f) as file:
        json_obj = ""
        lines = file.readlines()
        if len(lines) > 0:
            num_safe = _read_metadata_value(lines[0])
        if len(lines) > 1:
            num_unsafe = _read_metadata_value(lines[1])

        for line in lines:
            stripped = line.strip()
            if not stripped or stripped.startswith("#"):
                continue

            json_obj += line
            try:
                json_value = json.loads(json_obj)
            except json.JSONDecodeError:
                continue

            if isinstance(json_value, list):
                json_list.extend(json_value)
            else:
                json_list.append(json_value)
            json_obj = ""

    return json_list, num_safe, num_unsafe


def read_json_list_file(f):
    json_list, _, num_unsafe = read_json_file(f)
    return json_list, num_unsafe


def parse_span(span_text):
    match = span_pattern.match(span_text.strip())
    if match is None:
        return None, None, None
    return match.group("path"), match.group("span_start"), match.group("span_end")


def parse_trait_loc(loc_text):
    match = trait_loc_pattern.search(loc_text)
    if match is None:
        return None, None, None
    return match.group("path"), match.group("span_start"), match.group("span_end")

def format_functions(f, cve_id, commit_hash):
    jsonList, num_safe, num_unsafe = read_json_file(f)
    df = pd.DataFrame.from_records(jsonList)
    if not df.empty:
        df = df[df.apply(lambda x: "/.cargo/" not in x.header_span and "/rustc/" not in x.header_span, axis=1)]
    if not df.empty:
        df = df[df.apply(lambda x: ".rs" in x.header_span, axis=1) ]
    if not df.empty:
        # remove #[derive()] functions auto-generated by compilers
        df = df[df.apply(lambda x: x.header_span != x.body_span, axis=1) ]

    if df.empty:
        return df,0, 0
    spans = df['header_span'].apply(parse_span)
    df[['path', 'span_start', 'span_end']] = pd.DataFrame(spans.tolist(), index=df.index)
    df = df[df['path'].notna()]
    df["cve_id"] = cve_id
    df["hash"] = commit_hash
    df = df[ordered_columns]
    num_safe = len(df[df['unsafety']==False])
    num_unsafe = len(df[df['unsafety']==True])
    return df,num_safe, num_unsafe

def format_blocks(f, cve_id, commit_hash):
    jsonList, num_unsafe = read_json_list_file(f)

    df = pd.DataFrame.from_records(jsonList)
    if not df.empty:
        # Exclude code from installed crates
        df = df[df.apply(lambda x: "/.cargo/" not in x.block_span and "/rustc/" not in x.block_span, axis=1)]
    if not df.empty:
        # Include only Rust code files
        df = df[df.apply(lambda x: ".rs" in x.block_span, axis=1)]
    if df.empty:
        return df, 0
    spans = df['block_span'].apply(parse_span)
    df[['path', 'span_start', 'span_end']] = pd.DataFrame(spans.tolist(), index=df.index)
    df = df[df['path'].notna()]
    df["hash"] = commit_hash
    df["cve_id"] = cve_id
    df = df[ordered_columns_block]
    num_unsafe = len(df)
    return df, num_unsafe

def format_traits(f, package, cve_id, commit_hash):
    jsonList, _, _ = read_json_file(f)
    df = pd.DataFrame.from_records(jsonList)
    if df.empty:
        return df
    df['fn_id'] = df['name'].apply(lambda x : hash(x+cve_id) & sys.maxsize)
    spans = df['loc'].apply(parse_trait_loc)
    df[['path', 'span_start', 'span_end']] = pd.DataFrame(spans.tolist(), index=df.index)
    df = df[df['path'].notna()]
    del df["loc"]
    df["unsafety"] = ~df["safe"]
    df["package"] = package
    df["cve_id"] = cve_id
    df["hash"] = commit_hash
    df = df[['cve_id', 'hash', 'package', 'fn_id', 'path', 'span_start', 'span_end', 'name', 'safe', 'unsafety']]
    return df

def drop_tables():
    # drop all unsafe related tables
    mycursor = db.conn.cursor()
    mycursor.execute("DROP TABLE IF EXISTS unsafe_block;")
    mycursor.execute("DROP TABLE IF EXISTS unsafe_block_fix;")
    mycursor.execute("DROP TABLE IF EXISTS function;")
    mycursor.execute("DROP TABLE IF EXISTS function_fix;")
    mycursor.execute("DROP TABLE IF EXISTS total_safe_unsafe;")

def format_compile(analysis_dir, cve_id, hash):
    total_fn_safe = 0
    total_fn_unsafe = 0
    total_block_unsafe = 0
    df_func = pd.DataFrame()
    df_block = pd.DataFrame()
    analysis_root = Path(analysis_dir)

    for f_func in sorted(analysis_root.rglob('01_functions*')):
        if f_func.parent == analysis_root:
            continue
        df, num_safe, num_unsafe = format_functions(str(f_func), cve_id, hash)
        if not df.empty:
            df_func = pd.concat([df_func, df])
        total_fn_safe += num_safe
        total_fn_unsafe += num_unsafe

    for f_block in sorted(analysis_root.rglob('02_blocks_in_function*')):
        if f_block.parent == analysis_root:
            continue
        df, num_unsafe = format_blocks(str(f_block), cve_id, hash)
        if not df.empty:
            df_block = pd.concat([df_block, df])
        total_block_unsafe += num_unsafe

    return df_func, df_block, total_fn_safe, total_fn_unsafe, total_block_unsafe



@click.command()
@click.argument("commitfile", type=click.STRING)
def main(commitfile):
    drop_tables()

    df_fixes = pd.read_csv(commitfile)
    df_fixes.drop_duplicates(subset =['hash', 'repo_url'], keep = 'first', inplace = True)
    df_safe_cnt = pd.DataFrame(columns=["cve_id", "hash", "safe_func", "unsafe_func", "unsafe_block"])
    compile_failed = 0
    for _, row in df_fixes.iterrows():
        repo_url = row["repo_url"]
        cve_id = str(row["cve_id"])
        hash = row["hash"]
        full_project_name = get_full_project_name(repo_url)
        
        analysis_dir = f"{compiler_result}/{full_project_name}/{cve_id}/{hash}/"
        print(analysis_dir)
        if os.path.exists(analysis_dir):
            df_func, df_block, total_fn_safe, total_fn_unsafe, total_block_unsafe = format_compile(analysis_dir, cve_id, hash)
            write_database("function", df_func)
            write_database("unsafe_block", df_block)
            df_safe_cnt.loc[len(df_safe_cnt)] = {
                "cve_id": cve_id, 
                "hash":hash, 
                "safe_func":total_fn_safe, 
                "unsafe_func":total_fn_unsafe, 
                "unsafe_block":total_block_unsafe
            }
        else:
            compile_failed += 1

        analysis_dir = f"{compiler_result}/{full_project_name}/{cve_id}_fix/{hash}/"
        print(analysis_dir)
        if os.path.exists(analysis_dir):
            df_func, df_block, total_fn_safe, total_fn_unsafe, total_block_unsafe = format_compile(analysis_dir, cve_id, hash)
            write_database("unsafe_block_fix", df_block)
            write_database("function_fix", df_func)
        else:
            compile_failed += 1
        
    df_safe_cnt = df_safe_cnt[ordered_columns_num]
    write_database("total_safe_unsafe",df_safe_cnt)
    
if __name__ == '__main__':
    main()